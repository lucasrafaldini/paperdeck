function renderSvg(grid, options = {}) {
  const size = options.size || 64;
  const mono = options.mono || false;
  const palette = mono ? PALETTE_MONO : PALETTE;
  
  let rects = '';
  for (let r = 0; r < 16; r++) {
    const row = (grid && grid[r]) || '................';
    for (let c = 0; c < 16; c++) {
      const char = row[c] || '.';
      const fill = palette[char];
      if (fill && fill !== 'none') {
        rects += `<rect x="${c}" y="${r}" width="1" height="1" fill="${fill}"/>`;
      }
    }
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="${size}" height="${size}" style="shape-rendering:crispEdges;image-rendering:pixelated">${rects}</svg>`;
}

function getCharacter(id) {
  return CHARACTERS[id] || CHARACTERS.mametchi;
}

function getCharacterList() {
  return Object.keys(CHARACTERS).map((key) => ({
    id: key,
    name: CHARACTERS[key].name,
    desc: CHARACTERS[key].desc,
  }));
}

